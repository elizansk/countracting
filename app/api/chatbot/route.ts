export async function POST(request: Request) {
  const { message } = await request.json();
  const text = String(message ?? '').toLowerCase();
  if (!text.trim()) return NextResponse.json({ reply: 'Опишите вашу ситуацию, пожалуйста.' });

  for (const key of Object.keys(replies)) {
    if (text.includes(key)) {
      return NextResponse.json({ reply: replies[key] });
    }
  }
  return NextResponse.json({ reply: 'Похоже на ситуацию, которую нужно проверить. Не переводите деньги, не сообщайте коды, сохраните доказательства и откройте разделы «Схемы» или «Памятки».' });
}
